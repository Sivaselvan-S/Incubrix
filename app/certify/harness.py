"""7-step connector certification harness with evidence collection and drift canary."""

import time
from typing import Any

from sqlalchemy.orm import Session

from app.certify.drift import validate_response_schema
from app.connectors.registry import get_connector
from app.db.models import (
    CertificationModel,
    DestinationModel,
    generate_uuid,
    utcnow,
)
from app.logging import get_logger
from app.passport.engine import demote_destination, update_passport_success
from app.storage.minio_client import get_storage_client

logger = get_logger("app.certify.harness")


def run_certification(
    db: Session,
    destination_id: str,
    idempotency_key: str | None = None,
) -> dict[str, Any]:
    """Executes the standard 7-step certification pipeline for a destination.

    Steps:
      1. validate a test rendition
      2. publish with idempotency key
      3. drift canary: validate response against pinned JSON schema
      4. confirm live URL responds or get_status = live
      5. read status
      6. delete / unpublish
      7. confirm deleted/unpublished -> bundle evidence -> update Passport
    """
    dest = db.query(DestinationModel).filter(DestinationModel.id == destination_id).first()
    if not dest:
        raise ValueError(f"Destination '{destination_id}' not found.")

    connector_key = dest.connector_key
    connector = get_connector(connector_key)
    manifest = connector.manifest

    if idempotency_key is None:
        idempotency_key = f"cert_{dest.id[:8]}_{int(time.time())}"

    started_at = utcnow()
    steps_log: list[dict[str, Any]] = []
    timings: dict[str, float] = {}

    test_rendition = {
        "title": f"Certification Test Post [{idempotency_key}]",
        "body": "Automated verification test post generated by IncuBrix LongTail Passport certification harness.",
        "tags": ["test", "verification"],
    }
    destination_dict = dest.to_export_dict()
    destination_dict["id"] = dest.id
    connection_dict = {"destination_id": dest.id}

    # --------------------------------------------------------------------------
    # Step 1: Validate test rendition
    # --------------------------------------------------------------------------
    t0 = time.time()
    v_result = connector.validate(test_rendition, destination_dict, connection_dict)
    timings["step_1_validate_ms"] = round((time.time() - t0) * 1000, 2)
    steps_log.append({"step": "validate", "passed": v_result.get("ok", False), "details": v_result})

    if not v_result.get("ok", False):
        return _fail_certification(
            db, dest, "Validation step failed", steps_log, timings, started_at
        )

    # --------------------------------------------------------------------------
    # Step 2: Publish with idempotency key
    # --------------------------------------------------------------------------
    t1 = time.time()
    try:
        pub_result = connector.publish(
            rendition=test_rendition,
            destination=destination_dict,
            connection=connection_dict,
            idempotency_key=idempotency_key,
        )
        timings["step_2_publish_ms"] = round((time.time() - t1) * 1000, 2)
        steps_log.append({"step": "publish", "passed": True, "details": pub_result})
    except Exception as exc:
        steps_log.append({"step": "publish", "passed": False, "error": str(exc)})
        return _fail_certification(
            db, dest, f"Publish step failed: {exc}", steps_log, timings, started_at
        )

    platform_post_id = pub_result.get("platform_post_id", "")
    raw_response = pub_result.get("raw_response", pub_result)

    # --------------------------------------------------------------------------
    # Step 3: Drift Canary Schema Check
    # --------------------------------------------------------------------------
    is_valid_schema, fingerprint, drift_report = validate_response_schema(
        connector_key=connector_key,
        method="publish",
        response_data=raw_response,
    )
    steps_log.append(
        {
            "step": "drift_canary",
            "passed": is_valid_schema,
            "fingerprint": fingerprint,
            "drift_report": drift_report,
        }
    )

    if not is_valid_schema:
        # Schema drifted! Demote destination, write alert row, fail certification.
        reason = f"Drift Canary detected field mismatch in {connector_key}.publish: {drift_report.get('missing_fields', [])}"
        demote_destination(db, dest.id, reason=reason, error_code="CERT_DRIFT_DETECTED")
        return _fail_certification(
            db,
            dest,
            reason,
            steps_log,
            timings,
            started_at,
            drift_report=drift_report,
        )

    # For assisted tier, no further live platform calls are needed
    if manifest.tier == "assisted":
        return _complete_certification_success(
            db,
            dest,
            manifest,
            steps_log,
            timings,
            started_at,
            fingerprint,
            pub_result,
        )

    # --------------------------------------------------------------------------
    # Step 4: Confirm live
    # --------------------------------------------------------------------------
    t2 = time.time()
    status_result = connector.get_status(platform_post_id, connection_dict)
    timings["step_4_confirm_live_ms"] = round((time.time() - t2) * 1000, 2)
    is_live = status_result.get("status") in ("live", "published", "delivered")
    steps_log.append({"step": "confirm_live", "passed": is_live, "details": status_result})

    if not is_live:
        return _fail_certification(
            db, dest, f"Post did not confirm live: {status_result}", steps_log, timings, started_at
        )

    # --------------------------------------------------------------------------
    # Step 5: Read status
    # --------------------------------------------------------------------------
    steps_log.append({"step": "read_status", "passed": True, "status": status_result.get("status")})

    # --------------------------------------------------------------------------
    # Step 6: Delete / Unpublish
    # --------------------------------------------------------------------------
    t3 = time.time()
    try:
        del_result = connector.delete(platform_post_id, connection_dict)
        timings["step_6_delete_ms"] = round((time.time() - t3) * 1000, 2)
        steps_log.append(
            {"step": "delete", "passed": del_result.get("deleted", False), "details": del_result}
        )
    except Exception as exc:
        steps_log.append({"step": "delete", "passed": False, "error": str(exc)})
        return _fail_certification(
            db, dest, f"Delete step failed: {exc}", steps_log, timings, started_at
        )

    # --------------------------------------------------------------------------
    # Step 7: Confirm deleted / unpublished
    # --------------------------------------------------------------------------
    t4 = time.time()
    status_after_del = connector.get_status(platform_post_id, connection_dict)
    timings["step_7_confirm_deleted_ms"] = round((time.time() - t4) * 1000, 2)
    is_deleted = status_after_del.get("status") in ("deleted", "unpublished", "not_found")
    steps_log.append({"step": "confirm_deleted", "passed": is_deleted, "details": status_after_del})

    # --------------------------------------------------------------------------
    # Bundle Evidence, Store in MinIO/Storage, Promote Passport
    # --------------------------------------------------------------------------
    return _complete_certification_success(
        db,
        dest,
        manifest,
        steps_log,
        timings,
        started_at,
        fingerprint,
        pub_result,
    )


def _complete_certification_success(
    db: Session,
    dest: DestinationModel,
    manifest: Any,
    steps_log: list[dict[str, Any]],
    timings: dict[str, float],
    started_at: Any,
    fingerprint: str,
    pub_result: dict[str, Any],
) -> dict[str, Any]:
    storage = get_storage_client()
    now = utcnow()
    total_time_s = round((now - started_at).total_seconds(), 3)

    evidence_payload = {
        "destination_id": dest.id,
        "destination_name": dest.name,
        "connector_key": dest.connector_key,
        "timestamp": now.isoformat(),
        "total_seconds": total_time_s,
        "timings": timings,
        "steps": steps_log,
        "schema_fingerprint": fingerprint,
        "publication_result": pub_result,
        "screenshot_placeholder": f"Evidence snapshot captured for {dest.name}",
    }

    # Store evidence JSON to MinIO / local storage
    evidence_path = f"certification_pack/{dest.platform_key}/{dest.id}/evidence.json"
    evidence_uri = storage.save_evidence(evidence_path, evidence_payload)

    # Update Passport and promote level
    passport = update_passport_success(
        db,
        destination_id=dest.id,
        tier=manifest.tier,
        capabilities=manifest.capabilities,
        fingerprint=fingerprint,
        evidence_uri=evidence_uri,
    )

    # Record in certifications table
    cert_record = CertificationModel(
        id=generate_uuid(),
        destination_id=dest.id,
        started_at=started_at,
        finished_at=now,
        steps_json=steps_log,
        passed=True,
        evidence_uri=evidence_uri,
    )
    db.add(cert_record)
    db.commit()

    return {
        "status": "passed",
        "destination_id": dest.id,
        "level": passport.level,
        "health_score": passport.health_score,
        "evidence_uri": evidence_uri,
        "total_seconds": total_time_s,
        "timings": timings,
        "steps": steps_log,
    }


def _fail_certification(
    db: Session,
    dest: DestinationModel,
    reason: str,
    steps_log: list[dict[str, Any]],
    timings: dict[str, float],
    started_at: Any,
    drift_report: dict[str, Any] | None = None,
) -> dict[str, Any]:
    now = utcnow()
    total_time_s = round((now - started_at).total_seconds(), 3)

    storage = get_storage_client()
    evidence_payload = {
        "destination_id": dest.id,
        "destination_name": dest.name,
        "timestamp": now.isoformat(),
        "passed": False,
        "reason": reason,
        "total_seconds": total_time_s,
        "timings": timings,
        "steps": steps_log,
        "drift_report": drift_report,
    }
    evidence_path = f"certification_pack/{dest.platform_key}/{dest.id}/failure_evidence.json"
    evidence_uri = storage.save_evidence(evidence_path, evidence_payload)

    cert_record = CertificationModel(
        id=generate_uuid(),
        destination_id=dest.id,
        started_at=started_at,
        finished_at=now,
        steps_json=steps_log,
        passed=False,
        evidence_uri=evidence_uri,
        drift_report_json=drift_report,
    )
    db.add(cert_record)
    db.commit()

    return {
        "status": "failed",
        "destination_id": dest.id,
        "level": dest.level,
        "reason": reason,
        "evidence_uri": evidence_uri,
        "drift_report": drift_report,
        "steps": steps_log,
    }
